def create_release(apps, schema_editor):
    from releases.rendering import clean_html, html_to_markdown

    Release = apps.get_model('releases', 'Release')
    if Release.objects.filter(version=VERSION).exists():
        return
    # Historical models have no custom save(): clean the HTML and build the
    # Markdown copy here, as Release.save() would.
    article_html = clean_html(ARTICLE_HTML)
    Release.objects.create(
        version=VERSION,
        title=TITLE,
        summary=SUMMARY,
        article_html=article_html,
        article_markdown=html_to_markdown(article_html),
        released_at=datetime.date(2026, 9, 24),
        is_published=False,
    )


def delete_release(apps, schema_editor):
    Release = apps.get_model('releases', 'Release')
    Release.objects.filter(version=VERSION, notified_at__isnull=True).delete()


